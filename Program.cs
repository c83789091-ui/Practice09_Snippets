// Подключаем стандартную библиотеку System.
// Она нужна для работы с консолью и для генерации случайного числа через Random.
using System;

// Выводим название практической работы.
Console.WriteLine("Практическая 9. Сниппеты.");

// Указываем выбранный вариант.
// По заданию вариант 1 - сниппет prog, который создает структуру консольной программы.
Console.WriteLine("Вариант 1 - сниппет prog для структуры консольной программы.");

// Указываем, что дополнительно сделаны два своих сниппета.
Console.WriteLine("Также сделаны два своих сниппета: readint и pause.");
Console.WriteLine();

// Просим пользователя ввести имя.
// Это обычный пример консольного ввода.
Console.Write("Введите имя: ");

// Console.ReadLine() считывает строку из консоли.
// Если по какой-то причине пришло пустое значение null, используем слово "Пользователь".
string name = Console.ReadLine() ?? "Пользователь";

// Выводим приветствие с введенным именем.
Console.WriteLine("Привет, " + name + "!");

// Создаем объект Random и генерируем число от 1 до 10.
// В C# верхняя граница в Next(1, 11) не включается, поэтому 11 означает "до 10 включительно".
int randomNumber = new Random().Next(1, 11);

// Выводим случайное число.
Console.WriteLine("Случайное число от 1 до 10: " + randomNumber);

Console.WriteLine();

// Сообщаем, где лежат сами файлы сниппетов.
Console.WriteLine("Файлы сниппетов лежат рядом с этим Program.cs в папке Snippets.");

// Коротко пишем, как импортировать сниппеты в Visual Studio.
Console.WriteLine("Их импортируют в Visual Studio через Tools - Code Snippets Manager - Import.");

Console.WriteLine();
Console.WriteLine("Нажмите любую клавишу для выхода...");

// Ждем нажатия клавиши, чтобы консоль не закрылась сразу.
Console.ReadKey();
